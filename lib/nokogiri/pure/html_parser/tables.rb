      # xmlStrcasecmp over bytes (casemap only folds ASCII A-Z)
      def strcasecmp(a, b)
        a = a.b
        b = b.b
        i = 0
        loop do
          ca = a.getbyte(i) || 0
          cb = b.getbyte(i) || 0
          ca += 32 if ca >= 65 && ca <= 90
          cb += 32 if cb >= 65 && cb <= 90
          tmp = ca - cb
          return tmp if tmp != 0
          return 0 if cb == 0

          i += 1
        end
      end

      # htmlTagLookup (bsearch with xmlStrcasecmp over html40ElementTable)
      def tag_lookup(tag)
        return nil if tag.nil?

        tag = tag.to_s
        return TAG_CACHE[tag] if TAG_CACHE.key?(tag)

        key = tag.include?("\0") ? tag[0, tag.index("\0")] : tag
        lo = 0
        hi = ELEMENT_TABLE.length
        found = nil
        while lo < hi
          mid = (lo + hi) / 2
          c = strcasecmp(key, ELEMENT_TABLE[mid].name)
          if c < 0
            hi = mid
          elsif c > 0
            lo = mid + 1
          else
            found = ELEMENT_TABLE[mid]
            break
          end
        end
        TAG_CACHE[tag.frozen? ? tag : tag.dup.freeze] = found if TAG_CACHE.size < 10_000
        found
      end

