        hi = ENTITIES_TABLE.length
        while lo < hi
          mid = (lo + hi) / 2
          c = value - ENTITIES_TABLE[mid].value
          if c < 0
            hi = mid
          elsif c > 0
            lo = mid + 1
          else
            return ENTITIES_TABLE[mid]
          end
        end
        nil
      end

